test("historical prices recalculate auditable totals and source writes remain protected", async ({ page, request }) => {
  const headers = { "X-Observer-Request": "1" };
  await request.put("/api/pricebook", { headers, data: { rates: [] } });
  const initial = await (await request.post("/api/observability/recalculate", { headers })).json();
  await page.goto("/?tab=tokens");
  await page.getByText("统计审计与历史价格", { exact: true }).click();
  await page.getByLabel("模型名", { exact: true }).fill("gpt-5.5");
  const saved = page.waitForResponse((response) => response.url().endsWith("/api/pricebook") && response.request().method() === "PUT");
  await page.getByRole("button", { name: "添加价格", exact: true }).click();
  expect((await saved).status()).toBe(200);
  const recalculated = page.waitForResponse((response) => response.url().endsWith("/api/observability/recalculate"));
  await page.getByRole("button", { name: "重新计算", exact: true }).click();
  const result = await (await recalculated).json();
  expect(result.summary.tokens.effectiveTotal).toBe(initial.summary.tokens.effectiveTotal);
  expect(result.summary.tokens.cost.estimatedUsd).toBeLessThan(initial.summary.tokens.cost.estimatedUsd);
  const audit = await (await request.get("/api/audit")).json();
  expect(audit.runs[0].changeCount).toBeGreaterThan(0);
  expect(audit.runs[0].before.cost).toBeGreaterThan(audit.runs[0].after.cost);
  expect((await request.delete("/api/sessions/demo-session", { headers })).status()).toBe(403);
  await request.put("/api/pricebook", { headers, data: { rates: [] } });
  await request.post("/api/observability/recalculate", { headers });
});
